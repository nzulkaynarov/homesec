"""Очистка строк, которые полностью контролирует само устройство или ребёнок:
DHCP-hostname и поле «почему» на детской странице.

Зачем: эти строки попадают в текст событий журнала, а бот потом ВОССТАНАВЛИВАЕТ
из этого текста машинные поля — MAC устройства и номер заявки `[req#N]`.
Ребёнок, назвавший телефон «AA:BB:CC:DD:EE:FF» или написавший «req#7» в причине,
подменял бы объект, к которому родитель применяет кнопки под уведомлением.
Поэтому из недоверенного текста убираем ровно те формы, которые служат нам
якорями, плюс управляющие символы и скобки-разделители.

Это не защита от prompt injection (текст всё ещё может содержать инструкции для
LLM) — за это отвечает watchdog/analyst, которые не отдают имена устройств в
модель. Здесь — только однозначность разбора наших же сообщений.
"""

import re

_CONTROL = re.compile(r"[\x00-\x1f\x7f]")
_MAC = re.compile(r"\b[0-9A-Fa-f]{2}(?::[0-9A-Fa-f]{2}){5}\b")
_REQ = re.compile(r"req\s*#\s*\d+", re.IGNORECASE)
_SPACE = re.compile(r"\s+")

NAME_LIMIT = 48
REASON_LIMIT = 200


def clean_label(raw: str | None, limit: int = NAME_LIMIT) -> str:
    """Строка, безопасная для подстановки в текст события."""
    text = _CONTROL.sub(" ", raw or "")
    text = _MAC.sub("…", text)
    text = _REQ.sub("…", text)
    # Наши сообщения используют «…» для цитат и […] для машинных меток —
    # не даём подделать ни то, ни другое.
    for bad, good in (("«", '"'), ("»", '"'), ("[", "("), ("]", ")")):
        text = text.replace(bad, good)
    return _SPACE.sub(" ", text).strip()[:limit]
